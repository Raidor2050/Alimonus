// Regenerates supabase/seed.sql (starter Chordbook songs) from src/data/seed.ts.
// Usage: node --experimental-strip-types scripts/generate-seed-sql.ts
import { writeFileSync } from 'node:fs'
import { SEED_SONGS } from '../src/data/seed.ts'

const q = (v: unknown): string =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : Array.isArray(v) ? `array[${v.map(q).join(',')}]::text[]` : `'${String(v).replace(/'/g, "''")}'`

const rows = SEED_SONGS.map(
  (s) =>
    `  (${[s.id, s.title, s.artist, s.album, s.altTitles, s.durationMs, s.releaseYear, s.genre, s.key, s.bpm, s.description, s.credits, s.chordSheet, s.progression, s.chordSource, s.provenance].map(q).join(', ')})`,
)
const sql = `-- Starter Chordbook for Alimonus (generated by scripts/generate-seed-sql.ts).
-- Public-domain songs and Alimonus originals include full sheets; popular songs are metadata only.
-- Playlists, song states and roadmap items need real user ids, so \`npm run provision -- --seed\` adds those.
insert into public.songs (id, title, artist, album, alt_titles, duration_ms, release_year, genre, key, bpm, description, credits, chord_sheet, progression, chord_source, provenance)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`
writeFileSync('supabase/seed.sql', sql)
console.log(`wrote supabase/seed.sql (${SEED_SONGS.length} songs)`)
